using System;
using System.Buffers;
using System.Collections.Generic;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.AspNetCore.DataProtection.AuthenticatedEncryption;
using Microsoft.AspNetCore.DataProtection.Managed;
using Microsoft.AspNetCore.DataProtection.Tests.Internal;
using Xunit;

namespace Microsoft.AspNetCore.DataProtection.Tests.Aes;
public class AesAuthenticatedEncryptorTests
{
    [Theory]
    [InlineData(128)]
    [InlineData(192)]
    [InlineData(256)]
    public void Roundtrip_AesGcm_TryEncryptDecrypt_CorrectlyEstimatesDataLength(int symmetricKeySizeBits)
    {
        Secret kdk = new Secret(new byte[512 / 8]);
        IAuthenticatedEncryptor encryptor = new AesGcmAuthenticatedEncryptor(kdk, derivedKeySizeInBytes: symmetricKeySizeBits / 8);
        ArraySegment<byte> plaintext = new ArraySegment<byte>(Encoding.UTF8.GetBytes("plaintext"));
        ArraySegment<byte> aad = new ArraySegment<byte>(Encoding.UTF8.GetBytes("aad"));

        RoundtripEncryptionHelpers.AssertTryEncryptTryDecryptParity(encryptor, plaintext, aad);
    }

    [Fact]
    public void Constructor_PerformsSelfTest_ConsumesRandomBytes()
    {
        var genRandom = new SequentialGenRandom();
        byte initialValue = genRandom.CurrentValue;

        Secret kdk = new Secret(new byte[512 / 8]);
        _ = new AesGcmAuthenticatedEncryptor(kdk,
            derivedKeySizeInBytes: 256 / 8,
            genRandom: genRandom);

        // Indirectly testing that SelfTest ran by checking that random bytes were consumed
        Assert.NotEqual(initialValue, genRandom.CurrentValue);
    }
    [Theory]
    [InlineData(0, "BDF781756B2803ECA22A65EEC5647AC93FD2EE44D3718CDCD7C5715932DA1F53")]
    [InlineData(100, "2CF230E3CF111250532E9FE68A9B1E9517D75C5178B65DA9D6A4A47A716AEDFC")]
    [InlineData(2000, "16090A552F8B38BE7E9197F16E0A970FB362D93BB90A567E4CE07D85B6E5B95F")]
    public void Encrypt_AesGcm_KnownAnswer(int plaintextLength, string expectedSha256)
    {
        // Payloads were generated by the implementation prior to writing the random key modifier and nonce
        // directly into the output buffer; the output must remain byte-for-byte identical.
        var genRandom = new SequentialGenRandom();
        var kdk = new Secret(Enumerable.Range(0, 64).Select(i => (byte)i).ToArray());
        using var encryptor = new AesGcmAuthenticatedEncryptor(kdk, derivedKeySizeInBytes: 256 / 8, genRandom: genRandom);
        var plaintext = Enumerable.Range(0, plaintextLength).Select(i => (byte)(i * 7)).ToArray();
        var aad = Encoding.UTF8.GetBytes("additional authenticated data");

        genRandom.Reset();
        var byteArrayResult = encryptor.Encrypt(new ArraySegment<byte>(plaintext), new ArraySegment<byte>(aad));

        genRandom.Reset();
        var writer = new ArrayBufferWriter<byte>();
        encryptor.Encrypt(plaintext, aad, ref writer);
        var spanResult = writer.WrittenSpan.ToArray();

        Assert.Equal(expectedSha256, Convert.ToHexString(SHA256.HashData(byteArrayResult)));
        Assert.Equal(byteArrayResult, spanResult);
        Assert.Equal(plaintext, encryptor.Decrypt(new ArraySegment<byte>(byteArrayResult), new ArraySegment<byte>(aad)));
    }
}

