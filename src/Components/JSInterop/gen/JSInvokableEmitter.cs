using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Microsoft.JSInterop.SourceGenerators;

internal static class JSInvokableEmitter
{
    public const string HintName = "JSInvokableRegistrations.g.cs";

    private const string Prototype = "global::Microsoft.JSInterop.GeneratedInteropPrototype";

    public static string Emit(string assemblyName, ImmutableArray<JSInvokableMethod> methods)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable disable");
        builder.AppendLine("#pragma warning disable CA2255, CS0612, CS0618");
        builder.AppendLine();
        builder.AppendLine("namespace Microsoft.JSInterop.Generated");
        builder.AppendLine("{");
        builder.AppendLine("    [global::System.CodeDom.Compiler.GeneratedCode(\"Microsoft.JSInterop.SourceGenerators\", \"1.0.0.0\")]");
        // Obsolete context: allows registering methods and types marked [Obsolete(..., error: true)].
        builder.AppendLine("    [global::System.Obsolete]");
        builder.AppendLine("    internal static class __JSInvokableRegistrations");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void Register()");
        builder.AppendLine("        {");
        builder.AppendLine("            // Trimming removes the registrations when generated-only dispatch is disabled.");
        builder.AppendLine($"            if (!{Prototype}.GeneratedOnly)");
        builder.AppendLine("            {");
        builder.AppendLine("                return;");
        builder.AppendLine("            }");
        builder.AppendLine();
        EmitRegistrations(builder, "            ", assemblyName, methods);
        builder.AppendLine("        }");
        EmitInvokers(builder, "        ", methods);
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    /// <summary>
    /// Emits a partial declaration of a generic or non-accessible type whose static constructor registers
    /// the type's invokers. It runs for each closed type before its first instance is created.
    /// </summary>
    public static string EmitHost(HostInfo host, ImmutableArray<JSInvokableMethod> methods)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable disable");
        builder.AppendLine("#pragma warning disable CS0612, CS0618");
        builder.AppendLine();
        var indent = string.Empty;
        if (host.Namespace is not null)
        {
            builder.AppendLine($"namespace {host.Namespace}");
            builder.AppendLine("{");
            indent += "    ";
        }

        foreach (var declaration in host.Declarations)
        {
            builder.AppendLine($"{indent}{declaration}");
            builder.AppendLine($"{indent}{{");
            indent += "    ";
        }

        builder.AppendLine($"{indent}static {host.ConstructorName}()");
        builder.AppendLine($"{indent}{{");
        builder.AppendLine($"{indent}    // Trimming removes the registrations when generated-only dispatch is disabled.");
        builder.AppendLine($"{indent}    if (!{Prototype}.GeneratedOnly)");
        builder.AppendLine($"{indent}    {{");
        builder.AppendLine($"{indent}        return;");
        builder.AppendLine($"{indent}    }}");
        builder.AppendLine();
        EmitRegistrations(builder, indent + "    ", assemblyName: string.Empty, methods);
        builder.AppendLine($"{indent}}}");
        EmitInvokers(builder, indent, methods, obsoleteContext: true);

        for (var i = 0; i < host.Declarations.Length + (host.Namespace is null ? 0 : 1); i++)
        {
            indent = indent.Substring(4);
            builder.AppendLine($"{indent}}}");
        }

        return builder.ToString();
    }

    private static void EmitRegistrations(StringBuilder builder, string indent, string assemblyName, ImmutableArray<JSInvokableMethod> methods)
    {
        builder.AppendLine($"{indent}var registrations = {Prototype}.Shared;");
        for (var i = 0; i < methods.Length; i++)
        {
            var method = methods[i];
            var identifier = Literal(method.Identifier);
            var isAsync = method.ReturnKind is ReturnKind.Task or ReturnKind.TaskOfT ? "true" : "false";
            builder.AppendLine(method switch
            {
                { IsHidden: true } => $"{indent}registrations.RegisterNonInvokableInstance<{method.ContainingType}>({identifier});",
                { IsStatic: true } => $"{indent}registrations.RegisterStatic({Literal(assemblyName)}, {identifier}, {method.ParameterTypes.Length}, {InvokerName(i)}, isAsync: {isAsync});",
                _ => $"{indent}registrations.RegisterInstance<{method.ContainingType}>({identifier}, {method.ParameterTypes.Length}, {InvokerName(i)}, isAsync: {isAsync});",
            });
        }
    }

    private static void EmitInvokers(StringBuilder builder, string indent, ImmutableArray<JSInvokableMethod> methods, bool obsoleteContext = false)
    {
        for (var i = 0; i < methods.Length; i++)
        {
            if (!methods[i].IsHidden)
            {
                EmitInvoker(builder, indent, i, methods[i], obsoleteContext);
            }
        }
    }

    // Prefixed so that invokers emitted into user types do not collide with user members.
    private static string InvokerName(int index) => $"__JSInvokable_Invoke{index}";

    private static void EmitInvoker(StringBuilder builder, string indent, int index, JSInvokableMethod method, bool obsoleteContext)
    {
        builder.AppendLine();
        if (obsoleteContext)
        {
            // Host invokers live in the user's type, so each needs its own obsolete context.
            builder.AppendLine($"{indent}[global::System.Obsolete]");
        }

        builder.AppendLine($"{indent}private static global::System.Threading.Tasks.ValueTask<string> {InvokerName(index)}(global::Microsoft.JSInterop.JSRuntime runtime, object target, global::System.Text.Json.JsonElement[] args)");
        builder.AppendLine($"{indent}{{");

        // Every argument is deserialized before the call so that byte arrays are revived
        // before the dispatcher clears them.
        var identifier = Literal(method.Identifier);
        var arguments = new List<string>();
        for (var p = 0; p < method.ParameterTypes.Length; p++)
        {
            builder.AppendLine($"{indent}    var arg{p} = {Prototype}.ReadArgument<{method.ParameterTypes[p]}>(runtime, args[{p}], {identifier}, {p});");
            arguments.Add($"arg{p}");
        }

        var receiver = method.IsStatic ? method.ContainingType : $"(({method.ContainingType})target)";
        var call = $"{receiver}.{method.MethodName}({string.Join(", ", arguments)})";
        switch (method.ReturnKind)
        {
            case ReturnKind.Void:
                builder.AppendLine($"{indent}    {call};");
                builder.AppendLine($"{indent}    return default;");
                break;
            case ReturnKind.Task:
                builder.AppendLine($"{indent}    return {Prototype}.CompleteAsync({call});");
                break;
            case ReturnKind.TaskOfT:
                builder.AppendLine($"{indent}    return {Prototype}.SerializeResultAsync<{method.ResultType}>(runtime, {call});");
                break;
            default:
                builder.AppendLine($"{indent}    return {Prototype}.SerializeResult<{method.ResultType}>(runtime, {call});");
                break;
        }

        builder.AppendLine($"{indent}}}");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
