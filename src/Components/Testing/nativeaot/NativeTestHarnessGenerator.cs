using System;
using Microsoft.CodeAnalysis;

namespace Microsoft.AspNetCore.Components.Testing.NativeAot;

/// <summary>
/// Emits a self-contained E2E test harness into the application under test.
/// </summary>
/// <remarks>
/// <para>
/// The harness normally reaches an application through <c>ASPNETCORE_HOSTINGSTARTUPASSEMBLIES</c> and
/// <c>DOTNET_STARTUP_HOOKS</c>. Both name a foreign assembly and load it at startup, which a Native
/// AOT application cannot do — its image contains only what the compiler saw.
/// </para>
/// <para>
/// Instead of asking the application to reference the harness, this generator writes the two services
/// the harness needs into the application's own compilation, together with an assembly-level
/// <c>HostingStartup</c> attribute. The generated code depends only on
/// <c>Microsoft.Extensions.Hosting</c>, so the application gains no test-only runtime dependency.
/// </para>
/// <para>
/// Everything is gated on the <c>NativeTesting</c> MSBuild property, which the harness sets only on
/// the nested publish it runs for an application marked <c>NativeTesting="true"</c>. A normal build of
/// the same application never sees this generator at all.
/// </para>
/// </remarks>
[Generator]
public sealed class NativeTestHarnessGenerator : IIncrementalGenerator
{
    private const string EnabledPropertyName = "build_property.NativeTesting";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enabled = context.AnalyzerConfigOptionsProvider.Select(static (provider, _) =>
            provider.GlobalOptions.TryGetValue(EnabledPropertyName, out var value) &&
            string.Equals(value, "true", StringComparison.OrdinalIgnoreCase));

        context.RegisterSourceOutput(enabled, static (context, isEnabled) =>
        {
            if (isEnabled)
            {
                context.AddSource("NativeTestHarness.g.cs", HarnessSource);
            }
        });
    }

    private const string HarnessSource = """
        // <auto-generated/>
        #nullable enable

        [assembly: global::Microsoft.AspNetCore.Hosting.HostingStartup(
            typeof(global::Microsoft.AspNetCore.Components.Testing.NativeAot.Generated.NativeTestHarnessHostingStartup))]

        namespace Microsoft.AspNetCore.Components.Testing.NativeAot.Generated
        {
            /// <summary>
            /// Registers the harness services in the application under test.
            /// </summary>
            /// <remarks>
            /// The host always searches the entry assembly for <c>HostingStartup</c> attributes, so this
            /// runs with no environment variable and no startup hook. Only <c>GenericWebHostBuilder</c>
            /// executes hosting startups though, so an application built with <c>CreateSlimBuilder</c> or
            /// <c>CreateEmptyBuilder</c> must call
            /// <see cref="NativeTestHarnessServiceCollectionExtensions.AddNativeTestHarness"/> itself,
            /// behind the <c>NATIVE_TESTING</c> compilation symbol this build defines.
            /// </remarks>
            internal sealed class NativeTestHarnessHostingStartup : global::Microsoft.AspNetCore.Hosting.IHostingStartup
            {
                public void Configure(global::Microsoft.AspNetCore.Hosting.IWebHostBuilder builder)
                {
                    builder.ConfigureServices(static services => services.AddNativeTestHarness());
                }
            }

            /// <summary>Adds the harness services. Registration is idempotent.</summary>
            internal static class NativeTestHarnessServiceCollectionExtensions
            {
                public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddNativeTestHarness(
                    this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)
                {
                    global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(
                        services,
                        global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton<
                            global::Microsoft.Extensions.Hosting.IHostedService, NativeTestReadinessService>());
                    global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(
                        services,
                        global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Singleton<
                            global::Microsoft.Extensions.Hosting.IHostedService, NativeTestParentProcessWatcher>());

                    return services;
                }
            }

            /// <summary>
            /// Signals the harness once the application is listening, by posting to the URL in
            /// <c>E2E_READY_URL</c>. Inert when the variable is absent.
            /// </summary>
            internal sealed class NativeTestReadinessService : global::Microsoft.Extensions.Hosting.IHostedService
            {
                private readonly global::Microsoft.Extensions.Hosting.IHostApplicationLifetime _lifetime;

                public NativeTestReadinessService(global::Microsoft.Extensions.Hosting.IHostApplicationLifetime lifetime)
                {
                    _lifetime = lifetime;
                }

                public global::System.Threading.Tasks.Task StartAsync(global::System.Threading.CancellationToken cancellationToken)
                {
                    var readyUrl = global::System.Environment.GetEnvironmentVariable("E2E_READY_URL");
                    if (string.IsNullOrEmpty(readyUrl))
                    {
                        return global::System.Threading.Tasks.Task.CompletedTask;
                    }

                    _lifetime.ApplicationStarted.Register(() =>
                    {
                        // Fire and forget: the harness has its own timeout if this never arrives.
                        _ = NotifyReadyAsync(readyUrl!);
                    });

                    return global::System.Threading.Tasks.Task.CompletedTask;
                }

                public global::System.Threading.Tasks.Task StopAsync(global::System.Threading.CancellationToken cancellationToken)
                    => global::System.Threading.Tasks.Task.CompletedTask;

                private static async global::System.Threading.Tasks.Task NotifyReadyAsync(string url)
                {
                    const int MaxAttempts = 5;
                    var delay = global::System.TimeSpan.FromMilliseconds(200);

                    for (var attempt = 1; attempt <= MaxAttempts; attempt++)
                    {
                        try
                        {
                            using var client = new global::System.Net.Http.HttpClient();
                            client.Timeout = global::System.TimeSpan.FromSeconds(5);
                            var response = await client.PostAsync(url, content: null).ConfigureAwait(false);
                            if (response.IsSuccessStatusCode)
                            {
                                return;
                            }
                        }
                        catch
                        {
                            // Retry on any error.
                        }

                        if (attempt < MaxAttempts)
                        {
                            await global::System.Threading.Tasks.Task.Delay(delay).ConfigureAwait(false);
                            delay = global::System.TimeSpan.FromMilliseconds(delay.TotalMilliseconds * 2);
                        }
                    }
                }
            }

            /// <summary>
            /// Stops the application when the process named by <c>TEST_PARENT_PID</c> exits, so a crashed
            /// or cancelled test run cannot leave the application behind. Inert when the variable is absent.
            /// </summary>
            internal sealed class NativeTestParentProcessWatcher : global::Microsoft.Extensions.Hosting.BackgroundService
            {
                private readonly global::Microsoft.Extensions.Hosting.IHostApplicationLifetime _lifetime;
                private readonly int _parentPid;

                public NativeTestParentProcessWatcher(global::Microsoft.Extensions.Hosting.IHostApplicationLifetime lifetime)
                {
                    _lifetime = lifetime;
                    _parentPid = int.TryParse(global::System.Environment.GetEnvironmentVariable("TEST_PARENT_PID"), out var pid) ? pid : -1;
                }

                protected override async global::System.Threading.Tasks.Task ExecuteAsync(global::System.Threading.CancellationToken stoppingToken)
                {
                    if (_parentPid <= 0)
                    {
                        return;
                    }

                    try
                    {
                        var parent = global::System.Diagnostics.Process.GetProcessById(_parentPid);

                        while (!stoppingToken.IsCancellationRequested)
                        {
                            if (parent.HasExited)
                            {
                                _lifetime.StopApplication();
                                return;
                            }

                            await global::System.Threading.Tasks.Task.Delay(1000, stoppingToken).ConfigureAwait(false);
                        }
                    }
                    catch (global::System.ArgumentException)
                    {
                        // The parent is already gone.
                        _lifetime.StopApplication();
                    }
                    catch (global::System.OperationCanceledException)
                    {
                        // Normal shutdown.
                    }
                }
            }
        }
        """;
}
