using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Microsoft.AspNetCore.Components.Testing.Generators;

/// <summary>
/// Emits the MSTest binding for E2E UI tests into the consumer test assembly so the shipping
/// library itself needs no test-framework dependency. Two kinds of output are produced, both
/// gated on the consumer actually referencing MSTest:
/// <list type="number">
///   <item><description>
///     An always-on static class of <c>TestContext</c> convenience extensions (server-output /
///     screenshot / console attachment and traced-context creation) that bridge MSTest's
///     <c>TestContext</c> onto the library's framework-agnostic core.
///   </description></item>
///   <item><description>
///     Per <c>[UITest]</c>-annotated <c>partial</c> class: <c>[TestClass]</c>, a
///     <c>TestContext</c> property, and <c>[TestInitialize]</c>/<c>[TestCleanup]</c> hooks that
///     drive the agnostic <c>InitializeCoreAsync</c>/<c>CleanupCoreAsync</c> lifecycle and attach
///     server diagnostics.
///   </description></item>
/// </list>
/// </summary>
[Generator]
internal sealed class UITestGenerator : IIncrementalGenerator
{
    private const string UITestAttributeMetadataName =
        "Microsoft.AspNetCore.Components.Testing.Playwright.UITestAttribute";

    private const string TestContextMetadataName =
        "Microsoft.VisualStudio.TestTools.UnitTesting.TestContext";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // True only when the consuming compilation references MSTest. All MSTest-specific
        // output is gated on this so referencing the package from a non-test project is inert.
        var hasMSTest = context.CompilationProvider.Select(
            static (compilation, _) => compilation.GetTypeByMetadataName(TestContextMetadataName) is not null);

        // (1) Always-on TestContext bridge extensions.
        context.RegisterSourceOutput(hasMSTest, static (spc, hasMSTestRef) =>
        {
            if (hasMSTestRef)
            {
                spc.AddSource("E2EGeneratedTestContextExtensions.g.cs", ExtensionsSource);
            }
        });

        // (2) Per-[UITest] partial-class binding.
        var classes = context.SyntaxProvider.ForAttributeWithMetadataName(
                UITestAttributeMetadataName,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => GetUITestClass(ctx))
            .Where(static c => c is not null);

        context.RegisterSourceOutput(classes.Combine(hasMSTest), static (spc, pair) =>
        {
            if (pair.Right && pair.Left is UITestClass target)
            {
                spc.AddSource($"{target.HintName}.g.cs", EmitClassBinding(target));
            }
        });
    }

    private static UITestClass? GetUITestClass(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol type)
        {
            return null;
        }

        var ns = type.ContainingNamespace is { IsGlobalNamespace: false } n
            ? n.ToDisplayString()
            : null;

        var hintName = (ns is null ? type.Name : ns + "." + type.Name) + ".UITest";

        return new UITestClass(ns, type.Name, hintName);
    }

    private static string EmitClassBinding(UITestClass target)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.AspNetCore.Components.Testing.Infrastructure;");
        sb.AppendLine("using Microsoft.VisualStudio.TestTools.UnitTesting;");
        sb.AppendLine();

        if (target.Namespace is not null)
        {
            sb.Append("namespace ").Append(target.Namespace).AppendLine(";");
            sb.AppendLine();
        }

        sb.Append("[TestClass]").AppendLine();
        sb.Append("partial class ").AppendLine(target.Name);
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>The MSTest test context for the current test (injected by MSTest).</summary>");
        sb.AppendLine("    public TestContext TestContext { get; set; } = null!;");
        sb.AppendLine();
        sb.AppendLine("    [TestInitialize]");
        sb.AppendLine("    public global::System.Threading.Tasks.Task __UITestInitializeAsync()");
        sb.AppendLine("        => InitializeCoreAsync();");
        sb.AppendLine();
        sb.AppendLine("    [TestCleanup]");
        sb.AppendLine("    public async global::System.Threading.Tasks.Task __UITestCleanupAsync()");
        sb.AppendLine("    {");
        sb.AppendLine("        try");
        sb.AppendLine("        {");
        sb.AppendLine("            var __outcome = TestContext.CurrentTestOutcome;");
        sb.AppendLine("            var __failed = __outcome is not (UnitTestOutcome.Passed or UnitTestOutcome.Inconclusive);");
        sb.AppendLine("            SaveServerDiagnostics(__failed, TestContext.TestName ?? \"unknown\", TestContext.AddResultFile);");
        sb.AppendLine("        }");
        sb.AppendLine("        finally");
        sb.AppendLine("        {");
        sb.AppendLine("            await CleanupCoreAsync().ConfigureAwait(false);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private sealed record UITestClass
    {
        public UITestClass(string? @namespace, string name, string hintName)
        {
            Namespace = @namespace;
            Name = name;
            HintName = hintName;
        }

        public string? Namespace { get; }

        public string Name { get; }

        public string HintName { get; }
    }

    // Always-on bridge extensions emitted into the consumer assembly (which references MSTest,
    // Playwright, and this library). Placed in the Infrastructure namespace so existing
    // `using Microsoft.AspNetCore.Components.Testing.Infrastructure;` imports pick them up.
    private const string ExtensionsSource = """
        // <auto-generated/>
        #nullable enable

        namespace Microsoft.AspNetCore.Components.Testing.Infrastructure;

        using System;
        using System.Collections.Generic;
        using System.IO;
        using System.Threading.Tasks;
        using Microsoft.Playwright;
        using Microsoft.VisualStudio.TestTools.UnitTesting;

        /// <summary>
        /// Source-generated MSTest adapter over the framework-agnostic E2E testing core. Bridges
        /// MSTest's <see cref="TestContext"/> (outcome + result-file attachment) onto the library's
        /// delegate-based tracing/diagnostics APIs.
        /// </summary>
        internal static class E2EGeneratedTestContextExtensions
        {
            private static bool ShouldSave(TestContext test)
                => test.CurrentTestOutcome is not (UnitTestOutcome.Passed or UnitTestOutcome.Inconclusive);

            private static void AttachSaved(TestContext test, IReadOnlyList<string> paths)
            {
                foreach (var path in paths)
                {
                    test.AddResultFile(path);
                }

                if (paths.Count > 0)
                {
                    test.WriteLine("[E2E] Test artifacts saved:");
                    foreach (var path in paths)
                    {
                        test.WriteLine($"[E2E]   {Path.GetFileName(path)}");
                    }
                }
            }

            /// <summary>
            /// Takes a full-page screenshot of <paramref name="page"/> and attaches it to the test result.
            /// </summary>
            public static async Task AttachScreenshotAsync(this IPage page, TestContext test, string name = "screenshot.png")
            {
                ArgumentNullException.ThrowIfNull(page);
                ArgumentNullException.ThrowIfNull(test);

                var dir = E2EArtifactPaths.ForTest(test.TestName ?? "unknown");
                Directory.CreateDirectory(dir);
                var path = Path.Combine(dir, Guid.NewGuid().ToString("N") + "-" + name);
                await page.ScreenshotAsync(new() { Path = path, FullPage = true }).ConfigureAwait(false);
                test.AddResultFile(path);
            }

            /// <summary>
            /// Captures browser-console output from <paramref name="page"/> to a file that is attached
            /// to the test result when the returned handle is disposed.
            /// </summary>
            public static IDisposable CaptureBrowserConsole(this IPage page, TestContext test, string logName = "console.log")
            {
                ArgumentNullException.ThrowIfNull(page);
                ArgumentNullException.ThrowIfNull(test);

                var dir = E2EArtifactPaths.ForTest(test.TestName ?? "unknown");
                Directory.CreateDirectory(dir);
                var path = Path.Combine(dir, Guid.NewGuid().ToString("N") + "-" + logName);
                var writer = new StreamWriter(path) { AutoFlush = true };

                void Handler(object? _, IConsoleMessage msg) => writer.WriteLine($"[{msg.Type}] {msg.Text}");
                page.Console += Handler;

                return new ConsoleCapture(page, Handler, writer, path, test);
            }

            /// <summary>
            /// Creates a new traced browser context routed to <paramref name="server"/>. Trace/video
            /// artifacts are saved and attached unless the test passed.
            /// </summary>
            public static Task<TracedContext> NewTracedContextAsync(
                this IBrowser browser, TestContext test, ServerInstance server, BrowserNewContextOptions? options = null)
            {
                ArgumentNullException.ThrowIfNull(browser);
                ArgumentNullException.ThrowIfNull(test);
                ArgumentNullException.ThrowIfNull(server);

                var artifactDir = E2EArtifactPaths.ForTest(test.TestName ?? "unknown");
                return browser.NewTracedContextAsync(
                    server, artifactDir, () => ShouldSave(test), paths => AttachSaved(test, paths), options);
            }

            /// <summary>
            /// Starts tracing on an existing <paramref name="context"/> and returns a traced wrapper.
            /// </summary>
            public static Task<TracedContext> NewTracedContextAsync(
                IBrowserContext context, TestContext test, ServerInstance server, string? artifactDirOverride = null)
            {
                ArgumentNullException.ThrowIfNull(context);
                ArgumentNullException.ThrowIfNull(test);
                ArgumentNullException.ThrowIfNull(server);

                var artifactDir = artifactDirOverride ?? E2EArtifactPaths.ForTest(test.TestName ?? "unknown");
                return PlaywrightExtensions.NewTracedContextAsync(
                    context, artifactDir, () => ShouldSave(test), paths => AttachSaved(test, paths));
            }

            /// <summary>
            /// Starts tracing on an existing <paramref name="context"/>, saving/attaching artifacts
            /// on disposal unless the test passed.
            /// </summary>
            public static Task<TracingSession> TraceAsync(
                this IBrowserContext context, TestContext test, string artifactDir)
            {
                ArgumentNullException.ThrowIfNull(context);
                ArgumentNullException.ThrowIfNull(test);

                return context.TraceAsync(artifactDir, () => ShouldSave(test), paths => AttachSaved(test, paths));
            }

            private sealed class ConsoleCapture : IDisposable
            {
                private readonly IPage _page;
                private readonly EventHandler<IConsoleMessage> _handler;
                private readonly StreamWriter _writer;
                private readonly string _path;
                private readonly TestContext _test;

                public ConsoleCapture(IPage page, EventHandler<IConsoleMessage> handler, StreamWriter writer, string path, TestContext test)
                {
                    _page = page;
                    _handler = handler;
                    _writer = writer;
                    _path = path;
                    _test = test;
                }

                public void Dispose()
                {
                    try
                    {
                        _page.Console -= _handler;
                    }
                    catch
                    {
                        // page may have been closed
                    }

                    _writer.Dispose();
                    _test.AddResultFile(_path);
                }
            }
        }
        """;
}
