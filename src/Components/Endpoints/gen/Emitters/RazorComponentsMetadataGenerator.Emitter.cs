using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.AspNetCore.Components.Endpoints.Generators.Models;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Microsoft.AspNetCore.Components.Endpoints.Generators;

public sealed partial class RazorComponentsMetadataGenerator
{
    private const string GeneratorName = "Microsoft.AspNetCore.Components.Endpoints.Generators.RazorComponentsMetadataGenerator";
    private const string JSInvokableDescriptorType = "global::Microsoft.JSInterop.Infrastructure.JSInvokableMethodDescriptor";
    private const string ReadOnlyListType = "global::System.Collections.Generic.IReadOnlyList";
    private const string JsonResolverType = "global::System.Text.Json.Serialization.Metadata.IJsonTypeInfoResolver";
    private const string BuiltInJSInvokableDescriptorProviderType =
        "Microsoft.JSInterop.Infrastructure.BuiltInJSInvokableMethodDescriptors";

    private static void Emit(SourceProductionContext context, GenerationResult result)
    {
        foreach (var diagnostic in result.Diagnostics)
        {
            context.ReportDiagnostic(diagnostic.ToDiagnostic());
        }

        foreach (var model in result.Models)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            context.AddSource(GetHintName(model), SourceText.From(EmitContext(model), Encoding.UTF8));
        }
    }

    private static string GetHintName(MetadataContextModel model)
    {
        var builder = new StringBuilder();
        if (model.Namespace is not null)
        {
            builder.Append(model.Namespace).Append('.');
        }

        foreach (var containing in model.ContainingTypes)
        {
            builder.Append(containing.Name);
            if (!containing.TypeParameters.IsDefaultOrEmpty)
            {
                builder.Append('_').Append(containing.TypeParameters.Length);
            }

            builder.Append('.');
        }

        return builder.Append(model.TypeName).Append(".Metadata.g.cs").ToString();
    }

    internal static string EmitContext(MetadataContextModel model)
    {
        var writer = new CodeWriter();
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("#pragma warning disable CS0618 // Type or member is obsolete");
        writer.WriteLine("#pragma warning disable CS1998 // Async method lacks 'await' operators");
        writer.WriteLine("#pragma warning disable ASP0030 // Experimental framework metadata consumed by generated code");
        writer.WriteLine("#pragma warning disable ASPNETCORE9004 // Experimental Blazor Native AOT metadata");
        writer.WriteLine();

        if (model.Namespace is not null)
        {
            writer.WriteLine($"namespace {model.Namespace}");
            writer.OpenBrace();
        }

        foreach (var containing in model.ContainingTypes)
        {
            var typeParameters = containing.TypeParameters.IsDefaultOrEmpty
                ? string.Empty
                : $"<{string.Join(", ", containing.TypeParameters)}>";
            writer.WriteLine($"partial {containing.TypeKeyword} {containing.Name}{typeParameters}");
            foreach (var constraintClause in containing.ConstraintClauses)
            {
                writer.WriteLine(constraintClause);
            }

            writer.OpenBrace();
        }

        writer.WriteLine($"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{GeneratorName}\", null)]");
        writer.WriteLine($"partial {model.TypeKeyword} {model.TypeName}");
        writer.OpenBrace();

        writer.WriteLine("/// <inheritdoc />");
        writer.WriteLine($"public override {ReadOnlyListType}<{JSInvokableDescriptorType}> JSInvokableMethods => __Descriptors.JSInvokableMethods;");
        if (!model.DeclaresJsonTypeInfoResolver)
        {
            writer.WriteLine();
            writer.WriteLine("/// <inheritdoc />");
            writer.WriteLine($"public override {JsonResolverType}? JsonTypeInfoResolver => null;");
        }

        writer.WriteLine();
        writer.WriteLine("private static class __Descriptors");
        writer.OpenBrace();
        EmitJSInvokableMethods(
            writer,
            model.JSInvokableMethods,
            model.BuiltInJSInvokableDescriptorAssemblies);
        writer.CloseBrace();

        if (!model.JSInvokableMethods.IsDefaultOrEmpty)
        {
            writer.WriteLine();
            EmitJSInvocations(writer, model);
        }

        writer.CloseBrace();

        foreach (var _ in model.ContainingTypes)
        {
            writer.CloseBrace();
        }

        if (model.Namespace is not null)
        {
            writer.CloseBrace();
        }

        return writer.ToString();
    }

    private static void EmitJSInvokableMethods(
        CodeWriter writer,
        System.Collections.Immutable.ImmutableArray<JSInvokableMethodModel> methods,
        System.Collections.Immutable.ImmutableArray<string> builtInDescriptorAssemblies)
    {
        writer.WriteLine($"internal static readonly {JSInvokableDescriptorType}[] JSInvokableMethods =");
        writer.OpenBracket();

        for (var i = 0; i < methods.Length; i++)
        {
            var method = methods[i];
            writer.WriteLine($"new {JSInvokableDescriptorType}");
            writer.OpenBrace();
            writer.WriteLine($"AssemblyName = {SymbolHelpers.ToStringLiteral(method.AssemblyName)},");
            writer.WriteLine($"TargetType = typeof({method.TypeFullyQualifiedName}),");
            writer.WriteLine($"Identifier = {SymbolHelpers.ToStringLiteral(method.Identifier)},");
            writer.WriteLine($"IsStatic = {method.IsStatic.ToString().ToLowerInvariant()},");
            writer.WriteLine($"MethodKey = {SymbolHelpers.ToStringLiteral(method.MethodKey)},");
            var emittedKind = method.Kind switch
            {
                JSInvokableMethodKind.TypeCoverage => "OverrideBlocker",
                _ => method.Kind.ToString(),
            };
            writer.WriteLine($"Kind = global::Microsoft.JSInterop.Infrastructure.JSInvokableMethodKind.{emittedKind},");
            writer.WriteLine(method.Kind is JSInvokableMethodKind.OverrideBlocker or JSInvokableMethodKind.TypeCoverage
                ? "Invoke = static (_, _, _) => throw new global::System.InvalidOperationException(\"Applicability metadata cannot be invoked.\"),"
                : $"Invoke = __JSInvocations.Invoke_{i},");
            writer.CloseBraceWithComma();
        }

        for (var i = 0; i < builtInDescriptorAssemblies.Length; i++)
        {
            writer.WriteLine($".. GetBuiltInJSInvokableMethodDescriptors_{i}(null),");
        }

        writer.CloseBracketWithSemicolon();

        for (var i = 0; i < builtInDescriptorAssemblies.Length; i++)
        {
            writer.WriteLine();
            writer.WriteLine(
                "[global::System.Runtime.CompilerServices.UnsafeAccessor(" +
                "global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = \"GetDescriptors\")]");
            writer.WriteLine(
                $"private static extern {JSInvokableDescriptorType}[] GetBuiltInJSInvokableMethodDescriptors_{i}(" +
                "[global::System.Runtime.CompilerServices.UnsafeAccessorType(" +
                $"{SymbolHelpers.ToStringLiteral($"{BuiltInJSInvokableDescriptorProviderType}, {builtInDescriptorAssemblies[i]}")})] object? target);");
        }
    }

    private static void EmitJSInvocations(CodeWriter writer, MetadataContextModel model)
    {
        writer.WriteLine("private static class __JSInvocations");
        writer.OpenBrace();

        for (var i = 0; i < model.JSInvokableMethods.Length; i++)
        {
            if (model.JSInvokableMethods[i].Kind is JSInvokableMethodKind.OverrideBlocker or JSInvokableMethodKind.TypeCoverage)
            {
                continue;
            }

            if (i > 0)
            {
                writer.WriteLine();
            }

            EmitJSInvocation(writer, model.JSInvokableMethods[i], i);
        }

        writer.WriteLine();
        EmitJsonHelpers(writer);
        writer.CloseBrace();
    }

    private static void EmitJSInvocation(CodeWriter writer, JSInvokableMethodModel method, int index)
    {
        writer.WriteLine(
            $"internal static async global::System.Threading.Tasks.ValueTask<string?> Invoke_{index}(" +
            "object? __target, string __argsJson, global::System.Text.Json.JsonSerializerOptions __options)");
        writer.OpenBrace();

        var arguments = new List<string>(method.ParameterTypeFullyQualifiedNames.Length);
        writer.WriteLine("using var __document = global::System.Text.Json.JsonDocument.Parse(__argsJson);");
        writer.WriteLine("var __arguments = __document.RootElement;");
        writer.WriteLine(
            $"ValidateArguments(__arguments, {SymbolHelpers.ToStringLiteral(method.Identifier)}, " +
            $"{method.ParameterTypeFullyQualifiedNames.Length.ToString(CultureInfo.InvariantCulture)});");
        for (var i = 0; i < method.ParameterTypeFullyQualifiedNames.Length; i++)
        {
            var parameterType = method.ParameterTypeFullyQualifiedNames[i];
            writer.WriteLine(
                $"var __arg{i} = Read<{parameterType}>(__arguments, " +
                $"{SymbolHelpers.ToStringLiteral(method.Identifier)}, {i.ToString(CultureInfo.InvariantCulture)}, __options);");
            arguments.Add($"__arg{i}!");
        }

        var receiver = method.IsStatic
            ? method.TypeFullyQualifiedName
            : $"(({method.TypeFullyQualifiedName})__target!)";
        var call = $"{receiver}.{method.MethodName}({string.Join(", ", arguments)})";

        switch (method.ReturnKind)
        {
            case JSInvokableReturnKind.Void:
                writer.WriteLine($"{call};");
                writer.WriteLine("return null;");
                break;
            case JSInvokableReturnKind.Task:
            case JSInvokableReturnKind.ValueTask:
                writer.WriteLine($"await {call}.ConfigureAwait(false);");
                writer.WriteLine("return null;");
                break;
            case JSInvokableReturnKind.Value:
                writer.WriteLine($"var __result = {call};");
                writer.WriteLine($"return Write<{method.ReturnTypeFullyQualifiedName}>(__result, __options);");
                break;
            case JSInvokableReturnKind.TaskOfValue:
            case JSInvokableReturnKind.ValueTaskOfValue:
                writer.WriteLine($"var __result = await {call}.ConfigureAwait(false);");
                writer.WriteLine($"return Write<{method.ReturnTypeFullyQualifiedName}>(__result, __options);");
                break;
        }

        writer.CloseBrace();
    }

    private static void EmitJsonHelpers(CodeWriter writer)
    {
        writer.WriteLine("private static void ValidateArguments(in global::System.Text.Json.JsonElement arguments, string methodIdentifier, int expectedCount)");
        writer.OpenBrace();
        writer.WriteLine("if (arguments.ValueKind != global::System.Text.Json.JsonValueKind.Array)");
        writer.OpenBrace();
        writer.WriteLine("throw new global::System.Text.Json.JsonException(\"Invalid JSON\");");
        writer.CloseBrace();
        writer.WriteLine();
        writer.WriteLine("var actualCount = arguments.GetArrayLength();");
        writer.WriteLine("if (actualCount < expectedCount)");
        writer.OpenBrace();
        writer.WriteLine("throw new global::System.ArgumentException($\"The call to '{methodIdentifier}' expects '{expectedCount}' parameters, but received '{actualCount}'.\");");
        writer.CloseBrace();
        writer.WriteLine();
        writer.WriteLine("if (actualCount > expectedCount)");
        writer.OpenBrace();
        writer.WriteLine("throw new global::System.Text.Json.JsonException($\"Unexpected JSON token {GetTokenName(arguments[expectedCount])}. Ensure that the call to `{methodIdentifier}' is supplied with exactly '{expectedCount}' parameters.\");");
        writer.CloseBrace();
        writer.CloseBrace();
        writer.WriteLine();
        writer.WriteLine("private static global::System.Text.Json.JsonTokenType GetTokenName(in global::System.Text.Json.JsonElement argument)");
        writer.WriteLine("    => argument.ValueKind switch");
        writer.OpenBrace();
        writer.WriteLine("global::System.Text.Json.JsonValueKind.Object => global::System.Text.Json.JsonTokenType.StartObject,");
        writer.WriteLine("global::System.Text.Json.JsonValueKind.Array => global::System.Text.Json.JsonTokenType.StartArray,");
        writer.WriteLine("global::System.Text.Json.JsonValueKind.String => global::System.Text.Json.JsonTokenType.String,");
        writer.WriteLine("global::System.Text.Json.JsonValueKind.Number => global::System.Text.Json.JsonTokenType.Number,");
        writer.WriteLine("global::System.Text.Json.JsonValueKind.True => global::System.Text.Json.JsonTokenType.True,");
        writer.WriteLine("global::System.Text.Json.JsonValueKind.False => global::System.Text.Json.JsonTokenType.False,");
        writer.WriteLine("global::System.Text.Json.JsonValueKind.Null => global::System.Text.Json.JsonTokenType.Null,");
        writer.WriteLine("_ => global::System.Text.Json.JsonTokenType.None,");
        writer.CloseBraceWithSemicolon();
        writer.WriteLine();
        writer.WriteLine("private static T? Read<T>(in global::System.Text.Json.JsonElement arguments, string methodIdentifier, int index, global::System.Text.Json.JsonSerializerOptions options)");
        writer.OpenBrace();
        writer.WriteLine("var argument = arguments[index];");
        writer.WriteLine("if (argument.ValueKind == global::System.Text.Json.JsonValueKind.Object)");
        writer.OpenBrace();
        writer.WriteLine("var properties = argument.EnumerateObject();");
        writer.WriteLine("if (properties.MoveNext() && properties.Current.NameEquals(\"__dotNetObject\") &&");
        writer.WriteLine("    (!typeof(T).IsGenericType || typeof(T).GetGenericTypeDefinition() != typeof(global::Microsoft.JSInterop.DotNetObjectReference<>)))");
        writer.OpenBrace();
        writer.WriteLine("throw new global::System.InvalidOperationException($\"In call to '{methodIdentifier}', parameter of type '{typeof(T).Name}' at index {index + 1} must be declared as type 'DotNetObjectRef<{typeof(T).Name}>' to receive the incoming value.\");");
        writer.CloseBrace();
        writer.CloseBrace();
        writer.WriteLine();
        writer.WriteLine("var typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>)options.GetTypeInfo(typeof(T));");
        writer.WriteLine("return global::System.Text.Json.JsonSerializer.Deserialize(argument, typeInfo);");
        writer.CloseBrace();
        writer.WriteLine();
        writer.WriteLine("private static string Write<T>(T value, global::System.Text.Json.JsonSerializerOptions options)");
        writer.OpenBrace();
        writer.WriteLine("var typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>)options.GetTypeInfo(typeof(T));");
        writer.WriteLine("return global::System.Text.Json.JsonSerializer.Serialize(value, typeInfo);");
        writer.CloseBrace();
    }
}
