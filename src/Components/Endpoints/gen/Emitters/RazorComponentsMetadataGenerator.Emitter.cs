    private static void Emit(
        SourceProductionContext context,
        GenerationResult result,
        bool reflectionEnabledByDefault)
    {
        foreach (var diagnostic in result.Diagnostics)
        {
            context.ReportDiagnostic(diagnostic.ToDiagnostic(reflectionEnabledByDefault));
        }

        foreach (var model in result.Models)
        {
            context.CancellationToken.ThrowIfCancellationRequested();
            context.AddSource(GetHintName(model), SourceText.From(EmitContext(model), Encoding.UTF8));
        }
    }

    private static string GetHintName(MetadataContextModel model)
    {
        var builder = new StringBuilder();
        if (model.Namespace is not null)
        {
            builder.Append(model.Namespace).Append('.');
        }

        foreach (var containing in model.ContainingTypes)
        {
            builder.Append(containing.Name);
            if (!containing.TypeParameters.IsDefaultOrEmpty)
            {
                builder.Append('_').Append(containing.TypeParameters.Length);
            }

            builder.Append('.');
        }

        return builder.Append(model.TypeName).Append(".Metadata.g.cs").ToString();
    }

    internal static string EmitContext(MetadataContextModel model)
    {
        var writer = new CodeWriter();
        writer.WriteLine("// <auto-generated/>");
        writer.WriteLine("#nullable enable");
        writer.WriteLine("#pragma warning disable CS0618 // Type or member is obsolete");
        writer.WriteLine("#pragma warning disable CS1998 // Async method lacks 'await' operators");
        writer.WriteLine("#pragma warning disable ASP0030 // Experimental framework metadata consumed by generated code");
        writer.WriteLine("#pragma warning disable ASPNETCORE9004 // Experimental Blazor Native AOT metadata");
        writer.WriteLine();

        if (model.Namespace is not null)
        {
            writer.WriteLine($"namespace {model.Namespace}");
            writer.OpenBrace();
        }

        foreach (var containing in model.ContainingTypes)
        {
            var typeParameters = containing.TypeParameters.IsDefaultOrEmpty
                ? string.Empty
                : $"<{string.Join(", ", containing.TypeParameters)}>";
            writer.WriteLine($"partial {containing.TypeKeyword} {containing.Name}{typeParameters}");
            foreach (var constraintClause in containing.ConstraintClauses)
            {
                writer.WriteLine(constraintClause);
            }

            writer.OpenBrace();
        }

        writer.WriteLine($"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{GeneratorName}\", null)]");
        writer.WriteLine($"partial {model.TypeKeyword} {model.TypeName}");
        writer.OpenBrace();

        EmitOverrides(writer, model);
        writer.WriteLine();
        EmitDescriptorStore(writer, model);

        if (NeedsAccessors(model))
        {
            writer.WriteLine();
            EmitAccessors(writer, model);
        }

        if (!model.JSInvokableMethods.IsDefaultOrEmpty)
        {
            writer.WriteLine();
            EmitJSInvocations(writer, model);
        }

        writer.CloseBrace();

        foreach (var _ in model.ContainingTypes)
        {
            writer.CloseBrace();
        }

        if (model.Namespace is not null)
        {
            writer.CloseBrace();
        }

        return writer.ToString();
    }

    private static void EmitOverrides(CodeWriter writer, MetadataContextModel model)
    {
        writer.WriteLine($"/// <inheritdoc />");
        writer.WriteLine($"public override {ReadOnlyListType}<{ComponentDescriptorType}> Components => __Descriptors.Components;");
        writer.WriteLine();
        writer.WriteLine($"/// <inheritdoc />");
        writer.WriteLine($"public override {ReadOnlyListType}<{BindableTypeDescriptorType}> BindableTypes => __Descriptors.BindableTypes;");
        writer.WriteLine();
        writer.WriteLine($"/// <inheritdoc />");
        writer.WriteLine($"public override {ReadOnlyListType}<{JSInvokableDescriptorType}> JSInvokableMethods => __Descriptors.JSInvokableMethods;");

        if (!model.DeclaresJsonTypeInfoResolver)
        {
            writer.WriteLine();
            writer.WriteLine($"/// <inheritdoc />");
            writer.WriteLine($"public override {JsonResolverType}? JsonTypeInfoResolver => null;");
        }
    }

    private static void EmitDescriptorStore(CodeWriter writer, MetadataContextModel model)
    {
        writer.WriteLine(
            "[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(" +
            "\"Trimming\", \"IL2110\", Justification = " +
            "\"Generated component descriptors intentionally store statically analyzable member access delegates.\")]");
        writer.WriteLine(
            "[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(" +
            "\"Trimming\", \"IL2111\", Justification = " +
            "\"Generated component descriptors intentionally store statically analyzable member access delegates.\")]");
        writer.WriteLine("private static class __Descriptors");
        writer.OpenBrace();

        EmitComponents(
            writer,
            model.Components,
            model.BuiltInDescriptorAssemblies,
            model.BuiltInDescriptorFactories);
        writer.WriteLine();
        EmitBindableTypes(writer, model.BindableTypes);
        writer.WriteLine();
        EmitJSInvokableMethods(
            writer,
            model.JSInvokableMethods,
            model.BuiltInJSInvokableDescriptorAssemblies);

        writer.CloseBrace();
    }

    private static void EmitComponents(
        CodeWriter writer,
        ImmutableArray<DescribedComponentModel> components,
        ImmutableArray<string> builtInDescriptorAssemblies,
        ImmutableArray<BuiltInDescriptorFactoryModel> builtInDescriptorFactories)
    {
        writer.WriteLine($"internal static readonly {ComponentDescriptorType}[] Components =");
        writer.OpenBracket();

        for (var i = 0; i < components.Length; i++)
        {
            EmitComponent(writer, components[i], i);
        }

        for (var i = 0; i < builtInDescriptorAssemblies.Length; i++)
        {
            writer.WriteLine($".. GetBuiltInComponentDescriptors_{i}(null),");
        }

        for (var i = 0; i < builtInDescriptorFactories.Length; i++)
        {
            var typeArguments = string.Join(", ", builtInDescriptorFactories[i].TypeArgumentFullyQualifiedNames);
            writer.WriteLine($".. GetBuiltInComponentDescriptorFactory_{i}<{typeArguments}>(null),");
        }

        writer.CloseBracketWithSemicolon();

        for (var i = 0; i < builtInDescriptorAssemblies.Length; i++)
        {
            writer.WriteLine();
            writer.WriteLine(
                "[global::System.Runtime.CompilerServices.UnsafeAccessor(" +
                "global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = \"GetDescriptors\")]");
            writer.WriteLine(
                $"private static extern {ComponentDescriptorType}[] GetBuiltInComponentDescriptors_{i}(" +
                "[global::System.Runtime.CompilerServices.UnsafeAccessorType(" +
                $"{SymbolHelpers.ToStringLiteral($"{BuiltInDescriptorProviderType}, {builtInDescriptorAssemblies[i]}")})] object? target);");
        }

        for (var i = 0; i < builtInDescriptorFactories.Length; i++)
        {
            var factory = builtInDescriptorFactories[i];
            var typeParameters = string.Join(", ", Enumerable.Range(0, factory.TypeArgumentFullyQualifiedNames.Length)
                .Select(index => factory.TypeParameterDynamicallyAccessedMemberValues[index] == 0
                    ? $"T{index}"
                    : "[global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMembers(" +
                      "(global::System.Diagnostics.CodeAnalysis.DynamicallyAccessedMemberTypes)" +
                      $"({factory.TypeParameterDynamicallyAccessedMemberValues[index]}))] " +
                      $"T{index}"));
            writer.WriteLine();
            writer.WriteLine(
                "[global::System.Runtime.CompilerServices.UnsafeAccessor(" +
                $"global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = {SymbolHelpers.ToStringLiteral(factory.MethodName)})]");
            var constraints = factory.TypeParameterConstraintClauses.IsDefaultOrEmpty
                ? string.Empty
                : $" {string.Join(" ", factory.TypeParameterConstraintClauses)}";
            writer.WriteLine(
                $"private static extern {ComponentDescriptorType}[] GetBuiltInComponentDescriptorFactory_{i}<{typeParameters}>(" +
                "[global::System.Runtime.CompilerServices.UnsafeAccessorType(" +
                $"{SymbolHelpers.ToStringLiteral($"{BuiltInDescriptorProviderType}, {factory.AssemblyName}")})] object? target){constraints};");
        }
    }

    private static void EmitComponent(CodeWriter writer, DescribedComponentModel component, int index)
    {
        var type = component.TypeFullyQualifiedName;

        writer.WriteLine($"new {ComponentDescriptorType}");
        writer.OpenBrace();
        writer.WriteLine($"Type = typeof({type}),");

        if (component.CanConstruct)
        {
            writer.WriteLine($"CreateInstance = static __services => new {type}(),");
        }

        if (!component.Parameters.IsDefaultOrEmpty)
        {
            writer.WriteLine($"Parameters = new {ParameterDescriptorType}[]");
            writer.OpenBrace();
            for (var i = 0; i < component.Parameters.Length; i++)
            {
                EmitParameter(writer, component.Parameters[i], type, index, i);
            }

            writer.CloseBraceWithComma();
        }

        if (!component.Injectables.IsDefaultOrEmpty)
        {
            writer.WriteLine($"Injectables = new {InjectableDescriptorType}[]");
            writer.OpenBrace();
            for (var i = 0; i < component.Injectables.Length; i++)
            {
                EmitInjectable(writer, component.Injectables[i], type, index, i);
            }

            writer.CloseBraceWithComma();
        }

        if (!component.MetadataExpressions.IsDefaultOrEmpty)
        {
            writer.WriteLine("Metadata = new object[]");
            writer.OpenBrace();
            foreach (var expression in component.MetadataExpressions)
            {
                writer.WriteLine($"{expression},");
            }

            writer.CloseBraceWithComma();
        }

        writer.CloseBraceWithComma();
    }

    private static void EmitParameter(
        CodeWriter writer,
        ComponentParameterModel parameter,
        string componentType,
        int componentIndex,
        int index)
    {
        var read = parameter.RequiresGetAccessor
            ? $"__Accessors.GetParameter_{componentIndex}_{index}(({componentType})__target)"
            : $"(({componentType})__target).{parameter.Name}";
        var write = parameter.RequiresDamSuppression
            ? $"__Accessors.SetParameter_{componentIndex}_{index}(({componentType})__target, __value is null ? default! : ({parameter.PropertyTypeAnnotatedName})__value)"
            : parameter.RequiresSetAccessor
            ? $"__Accessors.SetParameter_{componentIndex}_{index}(({componentType})__target, __value is null ? default! : ({parameter.PropertyTypeAnnotatedName})__value)"
            : $"(({componentType})__target).{parameter.Name} = __value is null ? default! : ({parameter.PropertyTypeAnnotatedName})__value";

        writer.WriteLine($"new {ParameterDescriptorType}");
        writer.OpenBrace();
        writer.WriteLine($"Name = {SymbolHelpers.ToStringLiteral(parameter.Name)},");
        writer.WriteLine($"ParameterType = typeof({parameter.PropertyTypeFullyQualifiedName}),");
        writer.WriteLine($"Attribute = {parameter.AttributeExpression},");
        writer.WriteLine($"SetValue = static (__target, __value) => {write},");
        writer.WriteLine($"GetValue = static __target => {read},");

        if (parameter.IsPersistentState)
        {
            writer.WriteLine(
                $"GetStateSerializer = static __services => __services.GetService(" +
                $"typeof({StateSerializerType}<{parameter.PropertyTypeFullyQualifiedName}>)),");
        }

        writer.CloseBraceWithComma();
    }

    private static void EmitInjectable(
        CodeWriter writer,
        ComponentInjectableModel injectable,
        string componentType,
        int componentIndex,
        int index)
    {
        var write = injectable.RequiresSetAccessor
            ? $"__Accessors.SetInjectable_{componentIndex}_{index}(({componentType})__target, ({injectable.ServiceTypeFullyQualifiedName})__value!)"
            : $"(({componentType})__target).{injectable.Name} = ({injectable.ServiceTypeFullyQualifiedName})__value!";

        writer.WriteLine($"new {InjectableDescriptorType}");
        writer.OpenBrace();
        writer.WriteLine($"Name = {SymbolHelpers.ToStringLiteral(injectable.Name)},");
        writer.WriteLine($"ServiceType = typeof({injectable.ServiceTypeFullyQualifiedName}),");
        writer.WriteLine($"Attribute = {injectable.AttributeExpression},");
        writer.WriteLine($"SetValue = static (__target, __value) => {write},");
        writer.CloseBraceWithComma();
    }

    private static void EmitBindableTypes(CodeWriter writer, ImmutableArray<BindableTypeModel> bindableTypes)
    {
        if (bindableTypes.IsDefaultOrEmpty)
        {
            writer.WriteLine($"internal static readonly {BindableTypeDescriptorType}[] BindableTypes = [];");
            return;
        }

        writer.WriteLine($"internal static readonly {BindableTypeDescriptorType}[] BindableTypes =");
        writer.OpenBrace();

        for (var i = 0; i < bindableTypes.Length; i++)
        {
            EmitBindableType(writer, bindableTypes[i], i);
        }

        writer.CloseBraceWithSemicolon();
    }

    private static void EmitBindableType(CodeWriter writer, BindableTypeModel bindable, int index)
    {
        var type = bindable.TypeFullyQualifiedName;

        writer.WriteLine($"new {BindableTypeDescriptorType}");
        writer.OpenBrace();
        writer.WriteLine($"Type = typeof({type}),");

        if (!bindable.Members.IsDefaultOrEmpty)
        {
            writer.WriteLine($"Members = new {BindableMemberDescriptorType}[]");
            writer.OpenBrace();
            for (var i = 0; i < bindable.Members.Length; i++)
            {
                var member = bindable.Members[i];
                var read = member.RequiresGetAccessor
                    ? $"__Accessors.GetBindable_{index}_{i}(({type})__owner)"
                    : $"(({type})__owner).{member.Name}";

                writer.WriteLine($"new {BindableMemberDescriptorType}");
                writer.OpenBrace();
                writer.WriteLine($"Name = {SymbolHelpers.ToStringLiteral(member.Name)},");
                writer.WriteLine($"MemberType = typeof({member.MemberTypeFullyQualifiedName}),");
                writer.WriteLine($"GetValue = static __owner => {read},");
                writer.CloseBraceWithComma();
            }

            writer.CloseBraceWithComma();
        }

        if (!bindable.Indexers.IsDefaultOrEmpty)
        {
            writer.WriteLine($"Indexers = new {BindableIndexerDescriptorType}[]");
            writer.OpenBrace();
            foreach (var indexer in bindable.Indexers)
            {
                writer.WriteLine($"new {BindableIndexerDescriptorType}");
                writer.OpenBrace();
                writer.WriteLine($"IndexType = typeof({indexer.IndexTypeFullyQualifiedName}),");
                writer.WriteLine($"ValueType = typeof({indexer.ValueTypeFullyQualifiedName}),");
                writer.WriteLine(
                    $"GetValue = static (__owner, __index) => (({type})__owner)" +
                    $"[({indexer.IndexTypeFullyQualifiedName})__index!],");
                writer.CloseBraceWithComma();
            }

            writer.CloseBraceWithComma();
        }

        writer.CloseBraceWithComma();
    }

    private static void EmitJSInvokableMethods(
        CodeWriter writer,
        ImmutableArray<JSInvokableMethodModel> methods,
        ImmutableArray<string> builtInDescriptorAssemblies)
    {
        writer.WriteLine($"internal static readonly {JSInvokableDescriptorType}[] JSInvokableMethods =");
        writer.OpenBracket();

        for (var i = 0; i < methods.Length; i++)
        {
            var method = methods[i];
            writer.WriteLine($"new {JSInvokableDescriptorType}");
            writer.OpenBrace();
            writer.WriteLine($"AssemblyName = {SymbolHelpers.ToStringLiteral(method.AssemblyName)},");
            writer.WriteLine($"TargetType = typeof({method.TypeFullyQualifiedName}),");
            writer.WriteLine($"Identifier = {SymbolHelpers.ToStringLiteral(method.Identifier)},");
            writer.WriteLine($"IsStatic = {method.IsStatic.ToString().ToLowerInvariant()},");
            writer.WriteLine($"MethodKey = {SymbolHelpers.ToStringLiteral(method.MethodKey)},");
            var emittedKind = method.Kind switch
            {
                JSInvokableMethodKind.TypeCoverage => "OverrideBlocker",
                _ => method.Kind.ToString(),
            };
            writer.WriteLine($"Kind = global::Microsoft.JSInterop.Infrastructure.JSInvokableMethodKind.{emittedKind},");
            writer.WriteLine(method.Kind is JSInvokableMethodKind.OverrideBlocker or JSInvokableMethodKind.TypeCoverage
                ? "Invoke = static (_, _, _) => throw new global::System.InvalidOperationException(\"Applicability metadata cannot be invoked.\"),"
                : $"Invoke = __JSInvocations.Invoke_{i},");
            writer.CloseBraceWithComma();
        }

        for (var i = 0; i < builtInDescriptorAssemblies.Length; i++)
        {
            writer.WriteLine($".. GetBuiltInJSInvokableMethodDescriptors_{i}(null),");
        }

        writer.CloseBracketWithSemicolon();

        for (var i = 0; i < builtInDescriptorAssemblies.Length; i++)
        {
            writer.WriteLine();
            writer.WriteLine(
                "[global::System.Runtime.CompilerServices.UnsafeAccessor(" +
                "global::System.Runtime.CompilerServices.UnsafeAccessorKind.StaticMethod, Name = \"GetDescriptors\")]");
            writer.WriteLine(
                $"private static extern {JSInvokableDescriptorType}[] GetBuiltInJSInvokableMethodDescriptors_{i}(" +
                "[global::System.Runtime.CompilerServices.UnsafeAccessorType(" +
                $"{SymbolHelpers.ToStringLiteral($"{BuiltInJSInvokableDescriptorProviderType}, {builtInDescriptorAssemblies[i]}")})] object? target);");
        }
    }

    private static bool NeedsAccessors(MetadataContextModel model)
    {
        foreach (var component in model.Components)
        {
            foreach (var parameter in component.Parameters)
            {
                if (parameter.RequiresGetAccessor || parameter.RequiresSetAccessor || parameter.RequiresDamSuppression)
                {
                    return true;
                }
            }

            foreach (var injectable in component.Injectables)
            {
                if (injectable.RequiresSetAccessor)
                {
                    return true;
                }
            }
        }

        foreach (var bindable in model.BindableTypes)
        {
            foreach (var member in bindable.Members)
            {
                if (member.RequiresGetAccessor)
                {
                    return true;
                }
            }
        }

        return false;
    }

    // Members the generated code cannot touch directly — a Razor `@inject`, which the compiler emits
    // as a private property, being the common case — are reached through UnsafeAccessor. It resolves
    // at JIT/AOT compile time to a direct call, so it neither reflects nor generates code at runtime.
    private static void EmitAccessors(CodeWriter writer, MetadataContextModel model)
    {
        writer.WriteLine("private static class __Accessors");
        writer.OpenBrace();

        for (var c = 0; c < model.Components.Length; c++)
        {
            var component = model.Components[c];
            for (var i = 0; i < component.Parameters.Length; i++)
            {
                var parameter = component.Parameters[i];
                if (parameter.RequiresGetAccessor)
                {
                    EmitAccessor(writer, $"get_{parameter.Name}", $"GetParameter_{c}_{i}", parameter.DeclaringTypeFullyQualifiedName,
                        parameter.PropertyTypeAnnotatedName, isSetter: false);
                }

                if (parameter.RequiresDamSuppression)
                {
                    EmitDamSetter(writer, parameter, c, i);
                }
                else if (parameter.RequiresSetAccessor)
                {
                    EmitAccessor(writer, $"set_{parameter.Name}", $"SetParameter_{c}_{i}", parameter.DeclaringTypeFullyQualifiedName,
                        parameter.PropertyTypeAnnotatedName, isSetter: true);
                }
            }

            for (var i = 0; i < component.Injectables.Length; i++)
            {
                var injectable = component.Injectables[i];
                if (injectable.RequiresSetAccessor)
                {
                    EmitAccessor(writer, $"set_{injectable.Name}", $"SetInjectable_{c}_{i}", injectable.DeclaringTypeFullyQualifiedName,
                        injectable.ServiceTypeFullyQualifiedName, isSetter: true);
                }
            }
        }

        for (var b = 0; b < model.BindableTypes.Length; b++)
        {
            var bindable = model.BindableTypes[b];
            for (var i = 0; i < bindable.Members.Length; i++)
            {
                var member = bindable.Members[i];
                if (!member.RequiresGetAccessor)
                {
                    continue;
                }

                if (member.IsField)
                {
                    writer.WriteLine(
                        "[global::System.Runtime.CompilerServices.UnsafeAccessor(" +
                        "global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = " +
                        $"{SymbolHelpers.ToStringLiteral(member.Name)})]");
                    writer.WriteLine(
                        $"internal static extern ref {member.MemberTypeFullyQualifiedName} " +
                        $"GetBindableField_{b}_{i}({bindable.TypeFullyQualifiedName} target);");
                    writer.WriteLine(
                        $"internal static {member.MemberTypeFullyQualifiedName} GetBindable_{b}_{i}" +
                        $"({bindable.TypeFullyQualifiedName} target) => GetBindableField_{b}_{i}(target);");
                }
                else
                {
                    EmitAccessor(writer, $"get_{member.Name}", $"GetBindable_{b}_{i}",
                        bindable.TypeFullyQualifiedName, member.MemberTypeFullyQualifiedName, isSetter: false);
                }
            }
        }

        writer.CloseBrace();
    }

    private static void EmitAccessor(CodeWriter writer, string memberName, string accessorName, string targetType, string valueType, bool isSetter)
    {
        writer.WriteLine(
            "[global::System.Runtime.CompilerServices.UnsafeAccessor(" +
            "global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = " +
            $"{SymbolHelpers.ToStringLiteral(memberName)})]");

        writer.WriteLine(isSetter
            ? $"internal static extern void {accessorName}({targetType} target, {valueType} value);"
            : $"internal static extern {valueType} {accessorName}({targetType} target);");
    }

    private static void EmitDamSetter(CodeWriter writer, ComponentParameterModel parameter, int componentIndex, int index)
    {
        const string justification =
            "Generated component metadata resolves activation and parameter access without reflection.";

        writer.WriteLine(
            "[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(" +
            "\"Trimming\", \"IL2067\", Justification = " +
            $"{SymbolHelpers.ToStringLiteral(justification)})]");
        writer.WriteLine(
            "[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(" +
            "\"Trimming\", \"IL2110\", Justification = " +
            $"{SymbolHelpers.ToStringLiteral(justification)})]");
        writer.WriteLine(
            "[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(" +
            "\"Trimming\", \"IL2111\", Justification = " +
            $"{SymbolHelpers.ToStringLiteral(justification)})]");
        writer.WriteLine(
            $"internal static void SetParameter_{componentIndex}_{index}(" +
            $"{parameter.DeclaringTypeFullyQualifiedName} target, {parameter.PropertyTypeAnnotatedName} value) => " +
            $"target.{parameter.Name} = value;");
    }

    // One method per described [JSInvokable]. Deserialization and serialization happen on concrete type
    // arguments here, which is what lets the whole call be statically analyzed.
    private static void EmitJSInvocations(CodeWriter writer, MetadataContextModel model)
    {
        writer.WriteLine("private static class __JSInvocations");
        writer.OpenBrace();

        for (var i = 0; i < model.JSInvokableMethods.Length; i++)
        {
            if (model.JSInvokableMethods[i].Kind is JSInvokableMethodKind.OverrideBlocker or JSInvokableMethodKind.TypeCoverage)
            {
                continue;
            }

            if (i > 0)
            {
                writer.WriteLine();
            }

            EmitJSInvocation(writer, model.JSInvokableMethods[i], i);
        }

        writer.WriteLine();
        EmitJsonHelpers(writer);
        writer.CloseBrace();
    }

    private static void EmitJSInvocation(CodeWriter writer, JSInvokableMethodModel method, int index)
    {
        writer.WriteLine(
            $"internal static async global::System.Threading.Tasks.ValueTask<string?> Invoke_{index}(" +
            "object? __target, string __argsJson, global::System.Text.Json.JsonSerializerOptions __options)");
        writer.OpenBrace();

        var arguments = new List<string>(method.ParameterTypeFullyQualifiedNames.Length);
        writer.WriteLine("using var __document = global::System.Text.Json.JsonDocument.Parse(__argsJson);");
        writer.WriteLine("var __arguments = __document.RootElement;");
        writer.WriteLine(
            $"ValidateArguments(__arguments, {SymbolHelpers.ToStringLiteral(method.Identifier)}, " +
            $"{method.ParameterTypeFullyQualifiedNames.Length.ToString(CultureInfo.InvariantCulture)});");
        for (var i = 0; i < method.ParameterTypeFullyQualifiedNames.Length; i++)
        {
            var parameterType = method.ParameterTypeFullyQualifiedNames[i];
            writer.WriteLine(
                $"var __arg{i} = Read<{parameterType}>(__arguments, " +
                $"{SymbolHelpers.ToStringLiteral(method.Identifier)}, {i.ToString(CultureInfo.InvariantCulture)}, __options);");
            arguments.Add($"__arg{i}!");
        }

        var receiver = method.IsStatic
            ? method.TypeFullyQualifiedName
            : $"(({method.TypeFullyQualifiedName})__target!)";
        var call = $"{receiver}.{method.MethodName}({string.Join(", ", arguments)})";

        switch (method.ReturnKind)
        {
            case JSInvokableReturnKind.Void:
                writer.WriteLine($"{call};");
                writer.WriteLine("return null;");
                break;

            case JSInvokableReturnKind.Task:
            case JSInvokableReturnKind.ValueTask:
                writer.WriteLine($"await {call}.ConfigureAwait(false);");
                writer.WriteLine("return null;");
                break;

            case JSInvokableReturnKind.Value:
                writer.WriteLine($"var __result = {call};");
                writer.WriteLine($"return Write<{method.ReturnTypeFullyQualifiedName}>(__result, __options);");
                break;

